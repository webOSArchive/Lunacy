// The shell page's reach into Luna DE (main.js): the launcher's pages, launching, the cards'
// live views (up, hidden, snapshots, closed, popped out), and what the main process tells it.
"use strict";
const { contextBridge, ipcRenderer, webUtils } = require("electron");
const on = (channel) => (cb) => ipcRenderer.on(channel, (e, data) => cb(data));
contextBridge.exposeInMainWorld("lunade", {
	shell: () => ipcRenderer.invoke("lunade:shell"),
	launch: (entry) => ipcRenderer.invoke("lunade:launch", entry),
	maximize: (id) => ipcRenderer.invoke("lunade:maximize", id),
	cardView: () => ipcRenderer.invoke("lunade:cardview"),
	snapshot: (id) => ipcRenderer.invoke("lunade:snapshot", id),
	close: (id) => ipcRenderer.invoke("lunade:close", id),
	popOut: (id) => ipcRenderer.invoke("lunade:popout", id),
	devTools: (id) => ipcRenderer.invoke("lunade:devtools", id),
	reload: (id) => ipcRenderer.invoke("lunade:reload", id),
	ready: () => ipcRenderer.send("lunade:ready"),
	// Files dropped on the shell: their paths go to the main process to be installed.
	install: (files) => ipcRenderer.invoke("lunade:install", Array.from(files).map((f) => webUtils.getPathForFile(f)).filter(Boolean)),
	remove: (id) => ipcRenderer.invoke("lunade:remove", id),
	place: (rects, dashboardsOpen) => ipcRenderer.invoke("lunade:place", rects, dashboardsOpen),
	appMenu: () => ipcRenderer.invoke("lunade:appmenu"),
	back: () => ipcRenderer.invoke("lunade:back"),
	rotate: () => ipcRenderer.invoke("lunade:rotate"),
	device: (id) => ipcRenderer.invoke("lunade:device", id),
	screenNow: () => ipcRenderer.invoke("lunade:screen-now"),
	key: (key) => ipcRenderer.invoke("lunade:key", key),
	realKeyboard: () => ipcRenderer.invoke("lunade:real-keyboard"),
	keyboardSize: (size) => ipcRenderer.invoke("lunade:keyboard-size", size),
	onKeyboard: on("lunade:keyboard"),
	onToggleCard: on("lunade:toggle-card"),
	onLauncher: on("lunade:launcher"),
	onScreen: on("lunade:screen"),
	onPanelAdded: on("lunade:panel-added"),
	onPanelRemoved: on("lunade:panel-removed"),
	onBannerRemove: on("lunade:banner-remove"),
	onNetwork: on("lunade:network"),
	onHome: on("lunade:home"),
	onCardAdded: on("lunade:card-added"),
	onCardReady: on("lunade:card-ready"),
	onCardRemoved: on("lunade:card-removed"),
	onCardTitle: on("lunade:card-title"),
	onShow: on("lunade:show"),
	onApps: on("lunade:apps"),
	onBanner: on("lunade:banner"),
});
